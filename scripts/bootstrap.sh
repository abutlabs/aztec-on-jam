#!/usr/bin/env bash
# Set up everything the demo needs, at the pinned versions, on macOS or Linux.
#
#   scripts/bootstrap.sh              check and install; prints a table of what it found
#   scripts/bootstrap.sh --check      report only: install nothing, exit 1 if anything is missing
#   scripts/bootstrap.sh --rig        also lasair's in-process rig (needs access to abutlabs/lasair,
#                                     which is private; only services/privacy/check.sh and the
#                                     gas spike use it, never the demo)
#   scripts/bootstrap.sh --tools-md   print docs/TOOLS.md from the pins below, and exit
#
# The pins live here and nowhere else; docs/TOOLS.md is generated from them.
set -euo pipefail

NOIR=1.0.0-rc.5                 # nargo; Poseidon2 library v0.4.0 needs it
BB=5.0.0                        # Barretenberg: the version Noir rc.5 pins
RUST_NIGHTLY=nightly-2025-05-10 # jamswap's jam080-build (GP 0.8.0 blobs) pins it, with rust-src
NODE_MIN=20                     # the e2e run (puppeteer-core)
PYTHON_MIN=3.11                 # client, wallet backend, indexer (stdlib only)
PUPPETEER=25.16.0               # drives the installed Chrome; downloads no browser
CRYPTOGRAPHY_MIN=41             # Python: X25519, HKDF, AES-256-GCM for sealed notes (client/notecrypt.py)
LASAIR_IMAGE=ghcr.io/abutlabs/lasair:2.1.3   # the validators, pulled by jamswap's compose
OCAML=5.4.0                     # --rig only: lasair's in-process rig, and lasair for the native nets
POLKAJAM_NATIVE=v0.8.0          # the native nets (nets/jb.sh): paritytech/polkajam-releases; matches
                                # lasair main's PVM gas (the v0.8.0 vectors' cmov rule), so mixed nets agree
SIBLINGS="jamswap demo-wallet jamboree"  # cloned next to this repo; demo-wallet on jam, jamboree on lasair

HERE=$(cd "$(dirname "$0")/.." && pwd); SUB=$(cd "$HERE/.." && pwd)
MODE=install; RIG=0
for a in "$@"; do case "$a" in
  --check) MODE=check ;; --rig) RIG=1 ;;
  --tools-md) MODE=tools ;;
  *) sed -n 2,12p "$0"; exit 2 ;;
esac; done

if [ "$MODE" = tools ]; then cat <<EOF
# Tools

Generated by \`scripts/bootstrap.sh --tools-md\` from the pins at the top of that script; run
\`scripts/bootstrap.sh\` to check and install them. Do not edit by hand.

| Tool | Pinned | Installed by | Used by |
| --- | --- | --- | --- |
| Noir (nargo) | $NOIR | noirup, copied to \`~/.nargo/versions/nargo-$NOIR\` (\`NARGO=\` overrides) | circuits, \`client/privacy.py\` |
| Barretenberg (bb) | $BB | bbup, copied to \`~/.bb/versions/bb-$BB\` (\`BB=\` overrides) | proving; the vk the service embeds |
| Rust | stable, and $RUST_NIGHTLY with rust-src | rustup | the services, through jamswap's \`jam080-build\` |
| jam080-build | jamswap \`tools/jam080\` | \`cargo build --release\` there | GP 0.8.0 service blobs (crates.io \`jam-pvm-build\` targets GP 0.7.2) |
| The verifier | abutlabs/ultrahonk_verifier \`bb-v5\` @ a4b2a4af5d | cargo (git dependency) | refine: zkVerify's PR #9, bb $BB proofs |
| Node | $NODE_MIN or newer | your package manager | \`client/e2e\` |
| bb.js reference string (CRS) | the ranges bb.js 5.0.0 loads, pinned by sha256 | \`scripts/fetch-crs.sh\` into \`~/.cache/jam-privacy/crs\` | the wallet server serves it at \`/crs/\`: no CDN when the page proves |
| puppeteer-core | $PUPPETEER | \`npm install\` in \`client/e2e\` | the two-browser run; drives the installed Chrome (\`CHROME=\` overrides) |
| Python | $PYTHON_MIN or newer | your package manager | client, wallet backend, indexer, jamswap's JIP-2 tooling |
| cryptography (Python) | $CRYPTOGRAPHY_MIN or newer | pip, into \`out/pydeps\` if the system Python lacks it | sealed notes: X25519, HKDF, AES-256-GCM |
| Docker | any recent, daemon running | Docker Desktop or your package manager | the testnet (\`nets/\`) |
| lasair image | $LASAIR_IMAGE | pulled by jamswap's compose | the six validators |
| PolkaJam | jamswap's pinned nightly | downloaded when jamswap builds \`jamswap-pj-mixed:local\` | the genesis (\`gen-spec\`) and the PolkaJam nets |
| openssl | system | system | mint nonces in \`nets/demo.sh\` |
| jamboree | our fork, branch \`lasair\` | cloned next to this repo, \`cargo build --release\`; for Linux in Docker by \`scripts/jamboree-linux.sh\` | every net: \`jamboree rpc\` deploys, submits, reads; on the native nets it also launches the nodes |
| PolkaJam (native) | $POLKAJAM_NATIVE | the release tarball for this OS, into \`~/.cache/jam-privacy\` | the native nets (\`NET=jb-pj6\`, \`jb-mixed\`) |
| OCaml + dune | $OCAML (\`--rig\` only) | opam | lasair's \`bin/demo_deploy.exe\` (\`services/privacy/check.sh\`, the gas spike) and native lasair (\`NET=jb-lasair6\`, \`jb-mixed\`) |

Siblings, cloned next to this repo: $(for s in $SIBLINGS; do printf '`../%s` ' "$s"; done)(demo-wallet on its \`jam\` branch), and \`../lasair\` for \`--rig\`.
EOF
exit 0; fi

OS=$(uname -s); ARCH=$(uname -m)
ROWS=(); MISSING=0
row() { ROWS+=("$1|$2|$3|$4"); [ "$4" = ok ] || [ "$4" = installed ] || [ "$4" = optional ] || MISSING=$((MISSING + 1)); }
have() { command -v "$1" >/dev/null 2>&1; }
ver_ge() { [ "$(printf '%s\n%s\n' "$2" "$1" | sort -V | head -1)" = "$2" ]; }   # $1 >= $2
say() { printf '\033[1m==> %s\033[0m\n' "$*"; }
install() { [ "$MODE" = install ]; }

say "$OS $ARCH, repo $HERE"
for t in curl git; do have $t && row "$t" any "$(command -v $t)" ok || row "$t" any missing missing; done

# --- Rust -------------------------------------------------------------------------------
say Rust
if ! have rustup && install; then curl -sSf https://sh.rustup.rs | sh -s -- -y --profile minimal >/dev/null; fi
[ -f "$HOME/.cargo/env" ] && . "$HOME/.cargo/env"
if have rustup; then
  have cargo || { install && rustup toolchain install stable --profile minimal >/dev/null; } || true
  if ! rustup toolchain list | grep -q "^$RUST_NIGHTLY"; then
    install && rustup toolchain install "$RUST_NIGHTLY" --profile minimal --component rust-src >/dev/null
  fi
  install && rustup component add rust-src --toolchain "$RUST_NIGHTLY" >/dev/null 2>&1 || true
  row rust stable "$(rustc --version 2>/dev/null | cut -d' ' -f2)" "$(have rustc && echo ok || echo missing)"
  rustup toolchain list | grep -q "^$RUST_NIGHTLY" && row "rust nightly" "$RUST_NIGHTLY" present ok || row "rust nightly" "$RUST_NIGHTLY" missing missing
else row rustup any missing missing; fi

# --- Noir and Barretenberg, into versioned paths -----------------------------------------
say "Noir $NOIR and bb $BB"
mkdir -p "$HOME/.nargo/versions" "$HOME/.bb/versions"
NV=$HOME/.nargo/versions/nargo-$NOIR; BV=$HOME/.bb/versions/bb-$BB
if [ ! -x "$NV" ] && install; then
  have noirup || [ -x "$HOME/.nargo/bin/noirup" ] || curl -sL https://raw.githubusercontent.com/noir-lang/noirup/main/install | bash >/dev/null
  "$HOME/.nargo/bin/noirup" -v "$NOIR" >/dev/null 2>&1 && cp "$HOME/.nargo/bin/nargo" "$NV"
fi
[ -x "$NV" ] && row nargo "$NOIR" "$("$NV" --version | head -1 | awk '{print $4}')" ok || row nargo "$NOIR" missing missing
if [ ! -x "$BV" ] && install; then
  [ -x "$HOME/.bb/bbup" ] || curl -sL https://raw.githubusercontent.com/AztecProtocol/aztec-packages/refs/heads/next/barretenberg/bbup/install | bash >/dev/null
  "$HOME/.bb/bbup" -v "$BB" >/dev/null 2>&1 && cp "$HOME/.bb/bb" "$BV"
fi
[ -x "$BV" ] && row bb "$BB" "$("$BV" --version)" ok || row bb "$BB" missing missing

# --- Node, Python, Docker, openssl, Chrome: checked, not installed -------------------------
say "Node, Python, Docker, Chrome"
if have node && ver_ge "$(node --version | tr -d v)" "$NODE_MIN"; then row node ">= $NODE_MIN" "$(node --version)" ok; else row node ">= $NODE_MIN" "$(node --version 2>/dev/null || echo missing)" missing; fi
if have python3 && ver_ge "$(python3 -c 'import sys;print("%d.%d"%sys.version_info[:2])')" "$PYTHON_MIN"; then row python3 ">= $PYTHON_MIN" "$(python3 --version | cut -d' ' -f2)" ok; else row python3 ">= $PYTHON_MIN" "$(python3 --version 2>/dev/null || echo missing)" missing; fi
have openssl && row openssl any present ok || row openssl any missing missing
pyc() { python3 -c "import sys; sys.path.insert(0, '$HERE/out/pydeps'); import cryptography; print(cryptography.__version__)" 2>/dev/null; }
if [ -z "$(pyc)" ] && install && have python3; then python3 -m pip install -q --target "$HERE/out/pydeps" "cryptography>=$CRYPTOGRAPHY_MIN" >/dev/null 2>&1 || true; fi
v=$(pyc); if [ -n "$v" ] && ver_ge "$v" "$CRYPTOGRAPHY_MIN"; then row cryptography ">= $CRYPTOGRAPHY_MIN" "$v" ok; else row cryptography ">= $CRYPTOGRAPHY_MIN" "${v:-missing}" missing; fi
if have docker && docker info >/dev/null 2>&1; then row docker "daemon running" "$(docker --version | cut -d' ' -f3 | tr -d ,)" ok
elif have docker; then row docker "daemon running" "installed, daemon down" missing
else row docker "daemon running" missing missing; fi
CHROME=${CHROME:-}
for c in "$CHROME" "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" "$(command -v google-chrome || true)" "$(command -v chromium || true)" "$(command -v chromium-browser || true)"; do
  [ -n "$c" ] && [ -x "$c" ] && { CHROME=$c; break; }; done
[ -n "$CHROME" ] && [ -x "$CHROME" ] && row chrome any "$CHROME" ok || row chrome "any (the e2e run only)" "missing; set CHROME=" optional

# --- the sibling checkouts -----------------------------------------------------------------
say "Siblings in $SUB"
for s in $SIBLINGS; do
  if [ ! -d "$SUB/$s/.git" ] && [ ! -f "$SUB/$s/.git" ] && install; then git clone -q "https://github.com/abutlabs/$s" "$SUB/$s"; fi
  case "$s" in demo-wallet) br=jam ;; jamboree) br=lasair ;; *) br= ;; esac
  if [ -n "$br" ] && [ -e "$SUB/$s/.git" ]; then
    git -C "$SUB/$s" rev-parse --verify -q "$br" >/dev/null || { install && git -C "$SUB/$s" fetch -q origin "$br" && git -C "$SUB/$s" checkout -q -b "$br" "origin/$br"; } || true
    [ "$(git -C "$SUB/$s" branch --show-current)" = "$br" ] || { install && git -C "$SUB/$s" checkout -q "$br"; } || true
    [ "$(git -C "$SUB/$s" branch --show-current)" = "$br" ] && row "../$s" "$br branch" "$(git -C "$SUB/$s" log -1 --format=%h)" ok || row "../$s" "$br branch" "not on $br" missing
  else
    [ -e "$SUB/$s/.git" ] && row "../$s" checkout "$(git -C "$SUB/$s" log -1 --format=%h)" ok || row "../$s" checkout missing missing
  fi
done

# --- jam080-build, the circuits, the services, the e2e packages ----------------------------
J=$SUB/jamswap/tools/jam080/builder; JB=$J/target/release/jam080-build
if [ -d "$J" ]; then
  say jam080-build
  [ -x "$JB" ] || { install && cargo build --release -q --manifest-path "$J/Cargo.toml"; } || true
  [ -x "$JB" ] && row jam080-build "jamswap tools/jam080" built ok || row jam080-build "jamswap tools/jam080" "not built" missing
fi
if [ -x "$NV" ]; then
  say "circuits (Noir dependencies are fetched on the first compile)"
  for c in transfer hash_cli; do
    if (cd "$HERE/circuits/$c" && "$NV" compile --silence-warnings >/dev/null 2>&1); then row "circuit $c" compiles ok ok; else row "circuit $c" compiles failed missing; fi
  done
fi
if [ -x "$JB" ] && [ -x "$NV" ] && [ -x "$BV" ] && install; then
  say "the services"
  mkdir -p "$HERE/out"
  for svc in public-balance privacy; do
    if out=$("$JB" "$HERE/services/$svc" --out "$HERE/out" 2>&1 | grep '\.jam'); then row "service $svc" builds "$(echo "$out" | awk '{print $2}' | tr -d '(') bytes" ok; else row "service $svc" builds failed missing; fi
  done
fi
# the wallet page's provers: noir_js and bb.js bundled for the browser (demo-wallet jam/dist)
DW=$SUB/demo-wallet/jam
if have npm && [ -f "$DW/package.json" ]; then
  # built, and by build.mjs (its CRS from the page's own origin): an older bundle is rebuilt
  grep -q '/crs"' "$DW/dist/provers.js" 2>/dev/null || { install && (cd "$DW" && npm install --no-audit --no-fund >/dev/null 2>&1 && npm run build >/dev/null 2>&1); } || true
  grep -q '/crs"' "$DW/dist/provers.js" 2>/dev/null && row "wallet provers" "noir_js + bb.js" "built" ok || row "wallet provers" "noir_js + bb.js" "not built" missing
fi
# the provers' reference string, cached locally for the wallet server to serve (no CDN at demo time)
if have curl; then
  "$HERE/scripts/fetch-crs.sh" --check >/dev/null 2>&1 || { install && "$HERE/scripts/fetch-crs.sh" >/dev/null; } || true
  "$HERE/scripts/fetch-crs.sh" --check >/dev/null 2>&1 && row "prover CRS" "bb.js 5.0.0 ranges" "cached, hashes match" ok || row "prover CRS" "bb.js 5.0.0 ranges" missing missing
fi
if have npm && [ -f "$HERE/client/e2e/package.json" ]; then
  [ -d "$HERE/client/e2e/node_modules/puppeteer-core" ] || { install && (cd "$HERE/client/e2e" && npm install --no-audit --no-fund >/dev/null 2>&1); } || true
  [ -d "$HERE/client/e2e/node_modules/puppeteer-core" ] && row puppeteer-core "$PUPPETEER" "$(node -p "require('$HERE/client/e2e/node_modules/puppeteer-core/package.json').version")" ok || row puppeteer-core "$PUPPETEER" missing missing
fi
if have docker && docker info >/dev/null 2>&1; then
  docker image inspect "$LASAIR_IMAGE" >/dev/null 2>&1 || { install && docker pull -q "$LASAIR_IMAGE" >/dev/null; } || true
  docker image inspect "$LASAIR_IMAGE" >/dev/null 2>&1 && row "lasair image" "$LASAIR_IMAGE" pulled ok || row "lasair image" "$LASAIR_IMAGE" missing missing
fi

# --- the native nets (nets/jb.sh): jamboree, and PolkaJam's release binary ------------------
JBB=$SUB/jamboree/target/release/jamboree
if have cargo && [ -f "$SUB/jamboree/Cargo.toml" ]; then
  [ -x "$JBB" ] || { install && (cd "$SUB/jamboree" && cargo build --release -q 2>/dev/null); } || true
  [ -x "$JBB" ] && row jamboree "lasair branch, built" "$("$JBB" --version 2>/dev/null | head -1)" ok || row jamboree "lasair branch, built" "not built" missing
fi
case "$(uname -s)-$(uname -m)" in
  Darwin-arm64) PJP=macos-aarch64 ;; Darwin-x86_64) PJP=macos-x86_64 ;;
  Linux-aarch64|Linux-arm64) PJP=linux-aarch64 ;; *) PJP=linux-x86_64 ;;
esac
PJD=$HOME/.cache/jam-privacy/polkajam-$POLKAJAM_NATIVE; PJB=$PJD/polkajam-$POLKAJAM_NATIVE-$PJP/polkajam
if [ ! -x "$PJB" ] && install && have curl; then
  mkdir -p "$PJD" && curl -sfL "https://github.com/paritytech/polkajam-releases/releases/download/$POLKAJAM_NATIVE/polkajam-$POLKAJAM_NATIVE-$PJP.tgz" \
    | tar xz -C "$PJD" && { xattr -dr com.apple.quarantine "$PJD" 2>/dev/null || true; } || true
fi
if have docker && docker info >/dev/null 2>&1 && [ -f "$SUB/jamboree/Cargo.toml" ]; then
  "$HERE/scripts/jamboree-linux.sh" --check >/dev/null 2>&1 || { install && "$HERE/scripts/jamboree-linux.sh" >/dev/null; } || true
  "$HERE/scripts/jamboree-linux.sh" --check >/dev/null 2>&1 && row "jamboree (Linux)" "for the Docker nets" built ok || row "jamboree (Linux)" "for the Docker nets" "not built" missing
fi
[ -x "$PJB" ] && row "polkajam (native)" "$POLKAJAM_NATIVE" "$("$PJB" --version 2>/dev/null | head -1)" ok || row "polkajam (native)" "$POLKAJAM_NATIVE" missing missing

# --- --rig: lasair's in-process rig --------------------------------------------------------
if [ "$RIG" = 1 ]; then
  say "lasair's in-process rig"
  L=$SUB/lasair
  if [ ! -d "$L" ] && install; then git clone -q https://github.com/abutlabs/lasair "$L" || true; fi
  if [ -d "$L" ] && have opam; then
    eval "$(opam env 2>/dev/null)" || true
    if install; then
      [ "$(ocaml -vnum 2>/dev/null)" = "$OCAML" ] || opam switch create "$OCAML" -y >/dev/null 2>&1 || true
      eval "$(opam env --switch="$OCAML" 2>/dev/null)" || true
      opam install -y dune digestif yojson fmt alcotest >/dev/null 2>&1 || true
      for c in bandersnatch-ffi ed25519-ffi erasure-ffi quic-ffi hello-ffi; do (cd "$L/rust/$c" && cargo build --release -q) || true; done
      (cd "$L" && dune build bin/demo_deploy.exe bin/lasair_client.exe bin/lasair_reader.exe 2>/dev/null) || true
    fi
    [ -x "$L/_build/default/bin/demo_deploy.exe" ] && row "lasair rig" "OCaml $OCAML" built ok || row "lasair rig" "OCaml $OCAML" "not built" missing
    [ -x "$L/_build/default/bin/lasair_client.exe" ] && row "lasair (native)" "main, for jb-lasair6/jb-mixed" "$(git -C "$L" log -1 --format=%h)" ok || row "lasair (native)" "main" "not built" missing
  else row "lasair rig" "abutlabs/lasair + opam" "$( [ -d "$L" ] && echo 'no opam' || echo 'no access')" missing; fi
fi

# --- the table -----------------------------------------------------------------------------
printf '\n%-24s %-26s %-34s %s\n' TOOL WANTED FOUND STATUS
for r in "${ROWS[@]}"; do IFS='|' read -r a b c d <<<"$r"; printf '%-24s %-26s %-34s %s\n' "$a" "$b" "${c:0:34}" "$d"; done
if [ "$MISSING" -gt 0 ]; then echo; echo "$MISSING missing. $( [ "$MODE" = check ] && echo 'Run without --check to install what can be installed.' || echo 'Install the rest by hand (see docs/TOOLS.md), then run this again.')"; exit 1; fi
echo; echo "Ready. Next: nets/demo.sh up"
