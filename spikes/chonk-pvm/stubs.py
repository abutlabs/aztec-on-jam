"""stubs.cpp for every symbol the linked verifier still lacks (aztec-on-jam#62): each
function logs its name through chonk_trap and stops the refine; each data symbol (a vtable,
typeinfo, VTT or object) is zeroed storage. All of them sit on logging, exception or file
paths. Usage: stubs.py UNDEFINED_SYMBOLS DEMANGLED_SYMBOLS > stubs.cpp"""
import sys
raw = [l.strip() for l in open(sys.argv[1]) if l.strip()]
dem = [l.strip() for l in open(sys.argv[2]) if l.strip()]
print("// Generated by stubs.py from the linker's undefined symbols; see its docstring.")
print('extern "C" [[noreturn]] void chonk_trap(const char* what);')
for i, (r, d) in enumerate(zip(raw, dem)):
    data = d.startswith(("vtable for", "typeinfo for", "VTT for")) or (r.startswith("_Z") and "(" not in d)
    c = d.replace("\\", "\\\\").replace('"', '\\"')
    if data:
        print(f'extern "C" __attribute__((aligned(16))) const void* const stub_data_{i}[16] __asm__("{r}") = {{}};  // {c}')
    else:
        print(f'extern "C" void stub_fn_{i}(void) __asm__("{r}");')
        print(f'void stub_fn_{i}(void) {{ chonk_trap("{c}"); }}')
