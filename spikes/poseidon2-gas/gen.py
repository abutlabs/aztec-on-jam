#!/usr/bin/env python3
"""Writes p2/src/constants.rs: the Poseidon2 constants as compile-time field literals, from
client/poseidon2-bn254.json (Noir v1.0.0-rc.5's solver), the file the client uses.
  spikes/poseidon2-gas/gen.py"""
import json
from pathlib import Path
HERE = Path(__file__).resolve().parent
c = json.loads((HERE / "../../client/poseidon2-bn254.json").read_text())
lit = lambda h: f'MontFp!("{int(h, 16)}")'
rc = ",\n    ".join("[" + ", ".join(lit(x) for x in row) + "]" for row in c["round_constant"])
(HERE / "p2/src/constants.rs").write_text(f"""// Generated by spikes/poseidon2-gas/gen.py from client/poseidon2-bn254.json (Noir
// v1.0.0-rc.5's solver). Do not edit.
use ark_bn254::Fr;
use ark_ff::MontFp;

pub const ROUNDS_F: usize = {c["rounds_f"]};
pub const ROUNDS_P: usize = {c["rounds_p"]};
pub const DIAG: [Fr; 4] = [{", ".join(lit(x) for x in c["internal_matrix_diagonal"])}];
pub const RC: [[Fr; 4]; {len(c["round_constant"])}] = [
    {rc}
];
""")
